def generate_tax_summary_html(tax_result: Dict[str, Any], fy: str = "FY 2025-26", regime: str = "New Regime", user_label: str = "") -> str:
    kpis = f"""
    <div class="kpi-row">
      <div class="kpi"><div class="lbl">Gross Slab Income</div><div class="val">{format_inr(float(tax_result.get('gross_slab_income', 0)))}</div></div>
      <div class="kpi"><div class="lbl">Total Deductions</div><div class="val">{format_inr(float(tax_result.get('total_deduction', 0)))}</div></div>
      <div class="kpi"><div class="lbl">Net Taxable Income</div><div class="val">{format_inr(float(tax_result.get('taxable_income', 0)))}</div></div>
      <div class="kpi"><div class="lbl">Total Tax Liability</div><div class="val neg">{format_inr(float(tax_result.get('total_tax', 0)))}</div></div>
    </div>
    """
    inc_rows = "".join(
        f"<tr><td>{_esc(i.get('source', ''))}</td><td class='num'>{format_inr(float(i.get('annual', 0)))}</td></tr>"
        for i in tax_result.get("income_breakdown", [])
    ) or "<tr><td colspan='2'>No income sources logged.</td></tr>"

    adv_rows = ""
    for row in tax_result.get("advance_tax_schedule", []):
        cells = "".join(f"<td>{_esc(v)}</td>" for v in row.values())
        adv_rows += f"<tr>{cells}</tr>"
    adv_headers = "".join(f"<th>{_esc(k)}</th>" for k in (tax_result.get("advance_tax_schedule", [{}])[0].keys() if tax_result.get("advance_tax_schedule") else []))

    adv_html = ""
    if adv_rows:
        adv_html = f"<h2>Advance Tax Schedule</h2><table><thead><tr>{adv_headers}</tr></thead><tbody>{adv_rows}</tbody></table>"

    body = f"""
    {kpis}
    <p><strong>Balance Tax Due:</strong> {format_inr(float(tax_result.get('balance_due', 0)))} &middot; <strong>Regime:</strong> {_esc(regime)}</p>
    <h2>Income Sources Breakdown</h2>
    <table><thead><tr><th>Source</th><th class="num">Annual Amount</th></tr></thead><tbody>{inc_rows}</tbody></table>
    {adv_html}
    """
    return _wrap_html(f"Tax Summary — {fy}", f"{regime} · {user_label}", body)


