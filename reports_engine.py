def build_fy_summary_data(fy_tx_df: pd.DataFrame, fy_label: str, annual_recurring_income: float = 0.0) -> Dict[str, Any]:
    df = fy_tx_df.copy() if fy_tx_df is not None else pd.DataFrame()
    if not df.empty:
        if "transaction_type" not in df.columns:
            df["transaction_type"] = "Expense"
        df["transaction_type"] = df["transaction_type"].fillna("Expense").astype(str).str.strip().str.title()
        df["amount"] = pd.to_numeric(df["amount"], errors="coerce").fillna(0.0)
        df["Month_Key"] = pd.to_datetime(df["expense_date"], errors="coerce").dt.strftime("%Y-%m")
        exp_df = df[df["transaction_type"] != "Income"]
        inc_df = df[df["transaction_type"] == "Income"]
    else:
        exp_df = pd.DataFrame(columns=["Month_Key", "category", "amount"])
        inc_df = pd.DataFrame(columns=["Month_Key", "category", "amount"])

    total_exp = float(exp_df["amount"].sum()) if not exp_df.empty else 0.0
    total_inc_tx = float(inc_df["amount"].sum()) if not inc_df.empty else 0.0
    total_inc = total_inc_tx if total_inc_tx > 0 else float(annual_recurring_income or 0.0)
    net_savings = total_inc - total_exp
    savings_rate = (net_savings / total_inc * 100.0) if total_inc > 0 else 0.0

    monthly_exp = exp_df.groupby("Month_Key", as_index=False)["amount"].sum().rename(columns={"amount": "Expenses"}) if not exp_df.empty else pd.DataFrame(columns=["Month_Key", "Expenses"])
    monthly_inc = inc_df.groupby("Month_Key", as_index=False)["amount"].sum().rename(columns={"amount": "Income"}) if not inc_df.empty else pd.DataFrame(columns=["Month_Key", "Income"])
    monthly_df = pd.merge(monthly_exp, monthly_inc, on="Month_Key", how="outer").fillna(0.0)
    if not monthly_df.empty:
        monthly_df["Net Savings"] = monthly_df["Income"] - monthly_df["Expenses"]
        monthly_df = monthly_df.sort_values("Month_Key")

    cat_df = (
        exp_df.groupby("category", as_index=False)["amount"]
        .agg(Total="sum", Entries="count")
        .sort_values("Total", ascending=False)
        if not exp_df.empty
        else pd.DataFrame(columns=["category", "Total", "Entries"])
    )
    if not cat_df.empty and total_exp > 0:
        cat_df["Share %"] = (cat_df["Total"] / total_exp * 100.0).round(1)

    return {
        "fy_label": fy_label,
        "total_income": total_inc,
        "total_expense": total_exp,
        "net_savings": net_savings,
        "savings_rate": savings_rate,
        "active_months": len(monthly_df),
        "avg_monthly_spend": total_exp / max(1, len(monthly_df)),
        "monthly_df": monthly_df,
        "category_df": cat_df,
    }


