def _esc(val: Any) -> str:
    return html.escape(str(val if val is not None else ""))


def _wrap_html(title: str, subtitle: str, body: str) -> str:
    generated = datetime.datetime.now().strftime("%d %b %Y, %I:%M %p")
    return f"""<!DOCTYPE html>
<html lang="en">
<head><meta charset="utf-8"><title>{_esc(title)}</title>{_REPORT_CSS}</head>
<body>
  <div class="hdr">
    <div>
      <h1>🧭 FinCompass — {_esc(title)}</h1>
      <div class="meta">{_esc(subtitle)}</div>
    </div>
    <div class="meta">Generated: {generated}</div>
  </div>
  {body}
  <div class="footer">Generated by FinCompass Smart Financial Hub. Use Print (Ctrl+P / Cmd+P) → Save as PDF.</div>
</body>
</html>"""


def _df_to_excel_bytes(sheets: Dict[str, pd.DataFrame]) -> bytes:
    """Serialize one or more DataFrames into a formatted .xlsx workbook."""
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as writer:
        for name, df in sheets.items():
            safe_name = str(name)[:31]
            out_df = df if df is not None else pd.DataFrame()
            out_df.to_excel(writer, index=False, sheet_name=safe_name)
    return buf.getvalue()


