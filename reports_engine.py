def generate_debt_schedule_html(debts_df: pd.DataFrame, user_label: str = "") -> str:
    df = debts_df.copy() if debts_df is not None else pd.DataFrame()
    tot_prin = float(df["outstanding_principal"].sum()) if not df.empty and "outstanding_principal" in df.columns else 0.0
    tot_emi = float(df["emi_amount"].sum()) if not df.empty and "emi_amount" in df.columns else 0.0
    avg_rate = (
        float((df["outstanding_principal"] * df["interest_rate"]).sum() / tot_prin)
        if not df.empty and tot_prin > 0 and "interest_rate" in df.columns
        else 0.0
    )

    kpis = f"""
    <div class="kpi-row">
      <div class="kpi"><div class="lbl">Active Loans</div><div class="val">{len(df)}</div></div>
      <div class="kpi"><div class="lbl">Total Outstanding</div><div class="val neg">{format_inr(tot_prin)}</div></div>
      <div class="kpi"><div class="lbl">Total Monthly EMI</div><div class="val">{format_inr(tot_emi)}</div></div>
      <div class="kpi"><div class="lbl">Weighted Avg Rate</div><div class="val">{avg_rate:.2f}%</div></div>
    </div>
    """

    rows = ""
    if not df.empty:
        for _, r in df.iterrows():
            rows += (
                f"<tr><td>{_esc(r.get('loan_name', 'Loan'))}</td>"
                f"<td>{_esc(r.get('loan_type', ''))}</td>"
                f"<td class='num'>{format_inr(float(r.get('outstanding_principal', 0.0)))}</td>"
                f"<td class='num'>{float(r.get('interest_rate', 0.0)):.2f}%</td>"
                f"<td class='num'>{format_inr(float(r.get('emi_amount', 0.0)))}</td>"
                f"<td class='num'>{int(r.get('remaining_months', 0) or 0)} mo</td></tr>"
            )
    else:
        rows = "<tr><td colspan='6'>No active loans recorded — Debt-Free!</td></tr>"

    body = f"""
    {kpis}
    <h2>Active Loan Schedule ({len(df)})</h2>
    <table>
      <thead><tr><th>Loan Name</th><th>Type</th><th class="num">Outstanding</th><th class="num">Interest Rate</th><th class="num">Monthly EMI</th><th class="num">Remaining</th></tr></thead>
      <tbody>{rows}</tbody>
    </table>
    """
    return _wrap_html("Debt & Amortization Schedule", f"Liabilities Summary · {user_label}", body)


def generate_debt_schedule_excel(debts_df: pd.DataFrame) -> bytes:
    df = debts_df.copy() if debts_df is not None else pd.DataFrame()
    tot_prin = float(df["outstanding_principal"].sum()) if not df.empty and "outstanding_principal" in df.columns else 0.0
    tot_emi = float(df["emi_amount"].sum()) if not df.empty and "emi_amount" in df.columns else 0.0
    summary = pd.DataFrame([
        {"Metric": "Active Loans", "Value": len(df)},
        {"Metric": "Total Outstanding Principal (₹)", "Value": round(tot_prin, 2)},
        {"Metric": "Total Monthly EMI (₹)", "Value": round(tot_emi, 2)},
    ])
    keep = [c for c in ["loan_name", "loan_type", "outstanding_principal", "interest_rate", "emi_amount", "remaining_months"] if c in df.columns]
    return _df_to_excel_bytes({"Summary": summary, "Loans": df[keep] if keep else df})


