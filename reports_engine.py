def build_monthly_statement_data(
    month_tx_df: pd.DataFrame,
    month_key: str,
    recurring_monthly_income: float = 0.0,
    budget_df: Optional[pd.DataFrame] = None,
) -> Dict[str, Any]:
    df = month_tx_df.copy() if month_tx_df is not None else pd.DataFrame()
    if not df.empty:
        if "transaction_type" not in df.columns:
            df["transaction_type"] = "Expense"
        df["transaction_type"] = df["transaction_type"].fillna("Expense").astype(str).str.strip().str.title()
        df["amount"] = pd.to_numeric(df["amount"], errors="coerce").fillna(0.0)
        exp_df = df[df["transaction_type"] != "Income"]
        inc_df = df[df["transaction_type"] == "Income"]
    else:
        exp_df = pd.DataFrame(columns=["expense_date", "category", "description", "amount", "visibility", "transaction_type"])
        inc_df = pd.DataFrame(columns=["expense_date", "category", "description", "amount", "visibility", "transaction_type"])

    tx_expense = float(exp_df["amount"].sum()) if not exp_df.empty else 0.0
    tx_income = float(inc_df["amount"].sum()) if not inc_df.empty else 0.0
    total_income = tx_income if tx_income > 0 else float(recurring_monthly_income or 0.0)
    net_savings = total_income - tx_expense
    savings_rate = (net_savings / total_income * 100.0) if total_income > 0 else 0.0

    cat_df = (
        exp_df.groupby("category", as_index=False)["amount"]
        .agg(Spent="sum", Entries="count")
        .sort_values("Spent", ascending=False)
        if not exp_df.empty
        else pd.DataFrame(columns=["category", "Spent", "Entries"])
    )
    if not cat_df.empty and budget_df is not None and not budget_df.empty and "monthly_limit" in budget_df.columns:
        b_map = budget_df.set_index("category")["monthly_limit"].to_dict()
        cat_df["Monthly Budget"] = cat_df["category"].map(lambda c: float(b_map.get(c, 0.0)))
    elif not cat_df.empty:
        cat_df["Monthly Budget"] = 0.0

    try:
        dt = datetime.datetime.strptime(month_key, "%Y-%m")
        month_title = dt.strftime("%B %Y")
        fy_tag = get_indian_fy(dt.date())
    except Exception:
        month_title = month_key
        fy_tag = ""

    return {
        "month_key": month_key,
        "month_title": month_title,
        "fy_tag": fy_tag,
        "total_income": total_income,
        "tx_expense": tx_expense,
        "net_savings": net_savings,
        "savings_rate": savings_rate,
        "tx_count": len(df),
        "category_df": cat_df,
        "transactions_df": df,
    }


def generate_monthly_statement_html(data: Dict[str, Any], user_label: str = "") -> str:
    sav_cls = "pos" if data["net_savings"] >= 0 else "neg"
    kpis = f"""
    <div class="kpi-row">
      <div class="kpi"><div class="lbl">Total Income</div><div class="val">{format_inr(data['total_income'])}</div></div>
      <div class="kpi"><div class="lbl">Total Expenses</div><div class="val">{format_inr(data['tx_expense'])}</div></div>
      <div class="kpi"><div class="lbl">Net Savings</div><div class="val {sav_cls}">{format_inr(data['net_savings'])}</div></div>
      <div class="kpi"><div class="lbl">Savings Rate</div><div class="val">{data['savings_rate']:.1f}%</div></div>
    </div>
    """
    cat_rows = ""
    for _, r in data["category_df"].iterrows():
        b_val = float(r.get("Monthly Budget", 0.0))
        b_str = format_inr(b_val) if b_val > 0 else "—"
        cat_rows += (
            f"<tr><td>{_esc(r['category'])}</td>"
            f"<td class='num'>{int(r['Entries'])}</td>"
            f"<td class='num'>{format_inr(float(r['Spent']))}</td>"
            f"<td class='num'>{b_str}</td></tr>"
        )
    if not cat_rows:
        cat_rows = "<tr><td colspan='4'>No categorized expenses recorded for this month.</td></tr>"

    tx_rows = ""
    tx_df = data["transactions_df"]
    if not tx_df.empty:
        tx_sorted = tx_df.sort_values("expense_date", ascending=False) if "expense_date" in tx_df.columns else tx_df
        for _, r in tx_sorted.iterrows():
            dt_s = str(r.get("expense_date", ""))[:10]
            tx_rows += (
                f"<tr><td>{_esc(dt_s)}</td>"
                f"<td>{_esc(r.get('transaction_type', 'Expense'))}</td>"
                f"<td>{_esc(r.get('category', ''))}</td>"
                f"<td>{_esc(r.get('description', ''))}</td>"
                f"<td class='num'>{format_inr(float(r.get('amount', 0.0)))}</td></tr>"
            )
    else:
        tx_rows = "<tr><td colspan='5'>No transactions for this period.</td></tr>"

    body = f"""
    {kpis}
    <h2>Category Breakdown vs. Monthly Budget</h2>
    <table>
      <thead><tr><th>Category</th><th class="num">Entries</th><th class="num">Spent</th><th class="num">Monthly Budget</th></tr></thead>
      <tbody>{cat_rows}</tbody>
    </table>
    <h2>Itemized Transactions ({data['tx_count']})</h2>
    <table>
      <thead><tr><th>Date</th><th>Type</th><th>Category</th><th>Description</th><th class="num">Amount</th></tr></thead>
      <tbody>{tx_rows}</tbody>
    </table>
    """
    sub = f"Monthly Statement · {data['month_title']} ({data['fy_tag']})" + (f" · {user_label}" if user_label else "")
    return _wrap_html(f"Monthly Statement — {data['month_title']}", sub, body)


def generate_monthly_statement_excel(data: Dict[str, Any]) -> bytes:
    summary_df = pd.DataFrame([
        {"Metric": "Month", "Value": data["month_title"]},
        {"Metric": "Financial Year", "Value": data["fy_tag"]},
        {"Metric": "Total Income (₹)", "Value": round(data["total_income"], 2)},
        {"Metric": "Total Expenses (₹)", "Value": round(data["tx_expense"], 2)},
        {"Metric": "Net Savings (₹)", "Value": round(data["net_savings"], 2)},
        {"Metric": "Savings Rate (%)", "Value": round(data["savings_rate"], 2)},
        {"Metric": "Transaction Count", "Value": data["tx_count"]},
    ])
    tx_df = data["transactions_df"].copy()
    keep_cols = [c for c in ["expense_date", "transaction_type", "category", "description", "amount", "visibility", "username"] if c in tx_df.columns]
    if keep_cols:
        tx_df = tx_df[keep_cols]
    return _df_to_excel_bytes({
        "Summary": summary_df,
        "Category Breakdown": data["category_df"],
        "Transactions": tx_df,
    })


