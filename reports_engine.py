def generate_portfolio_statement_html(inv_df: pd.DataFrame, user_label: str = "") -> str:
    df = inv_df.copy() if inv_df is not None else pd.DataFrame()
    tot_inv = float(df["investment_amount"].sum()) if not df.empty and "investment_amount" in df.columns else 0.0
    tot_val = float(df["current_value"].sum()) if not df.empty and "current_value" in df.columns else 0.0
    gain = tot_val - tot_inv
    ret_pct = (gain / tot_inv * 100.0) if tot_inv > 0 else 0.0
    g_cls = "pos" if gain >= 0 else "neg"

    kpis = f"""
    <div class="kpi-row">
      <div class="kpi"><div class="lbl">Current Value</div><div class="val">{format_inr(tot_val)}</div></div>
      <div class="kpi"><div class="lbl">Total Invested</div><div class="val">{format_inr(tot_inv)}</div></div>
      <div class="kpi"><div class="lbl">Unrealised Gain</div><div class="val {g_cls}">{format_inr(gain)}</div></div>
      <div class="kpi"><div class="lbl">Total Return</div><div class="val {g_cls}">{ret_pct:+.1f}%</div></div>
    </div>
    """
    alloc_rows = ""
    if not df.empty and "investment_type" in df.columns:
        grp = df.groupby("investment_type", as_index=False).agg(
            Invested=("investment_amount", "sum"),
            Current=("current_value", "sum"),
            Count=("current_value", "count"),
        ).sort_values("Current", ascending=False)
        for _, r in grp.iterrows():
            wt = (float(r["Current"]) / tot_val * 100.0) if tot_val > 0 else 0.0
            alloc_rows += (
                f"<tr><td>{_esc(r['investment_type'])}</td><td class='num'>{int(r['Count'])}</td>"
                f"<td class='num'>{format_inr(float(r['Invested']))}</td>"
                f"<td class='num'>{format_inr(float(r['Current']))}</td>"
                f"<td class='num'>{wt:.1f}%</td></tr>"
            )
    else:
        alloc_rows = "<tr><td colspan='5'>No investment holdings recorded.</td></tr>"

    hold_rows = ""
    if not df.empty:
        for _, r in df.sort_values("current_value", ascending=False).iterrows():
            name = r.get("resolved_name") or r.get("description") or r.get("platform") or "Holding"
            rp = float(r.get("returns_pct", 0.0) or 0.0)
            hold_rows += (
                f"<tr><td>{_esc(name)}</td><td>{_esc(r.get('investment_type', ''))}</td>"
                f"<td>{_esc(r.get('platform', ''))}</td>"
                f"<td class='num'>{format_inr(float(r.get('investment_amount', 0.0)))}</td>"
                f"<td class='num'>{format_inr(float(r.get('current_value', 0.0)))}</td>"
                f"<td class='num'>{rp:+.1f}%</td></tr>"
            )
    else:
        hold_rows = "<tr><td colspan='6'>No holdings available.</td></tr>"

    body = f"""
    {kpis}
    <h2>Asset Allocation</h2>
    <table>
      <thead><tr><th>Asset Class</th><th class="num">Holdings</th><th class="num">Invested</th><th class="num">Current Value</th><th class="num">Weight</th></tr></thead>
      <tbody>{alloc_rows}</tbody>
    </table>
    <h2>Holdings Detail ({len(df)})</h2>
    <table>
      <thead><tr><th>Holding</th><th>Type</th><th>Platform</th><th class="num">Invested</th><th class="num">Current Value</th><th class="num">Return</th></tr></thead>
      <tbody>{hold_rows}</tbody>
    </table>
    """
    return _wrap_html("Portfolio Statement", f"Investment Holdings Valuation · {user_label}", body)


def generate_portfolio_statement_excel(inv_df: pd.DataFrame) -> bytes:
    df = inv_df.copy() if inv_df is not None else pd.DataFrame()
    tot_inv = float(df["investment_amount"].sum()) if not df.empty and "investment_amount" in df.columns else 0.0
    tot_val = float(df["current_value"].sum()) if not df.empty and "current_value" in df.columns else 0.0
    summary = pd.DataFrame([
        {"Metric": "Total Invested (₹)", "Value": round(tot_inv, 2)},
        {"Metric": "Current Portfolio Value (₹)", "Value": round(tot_val, 2)},
        {"Metric": "Unrealised Gain/Loss (₹)", "Value": round(tot_val - tot_inv, 2)},
        {"Metric": "Holdings Count", "Value": len(df)},
    ])
    keep = [c for c in ["description", "resolved_name", "platform", "investment_type", "investment_amount", "current_value", "unrealized_gain", "returns_pct", "units", "market_cap", "sector_segment"] if c in df.columns]
    return _df_to_excel_bytes({"Summary": summary, "Holdings": df[keep] if keep else df})


